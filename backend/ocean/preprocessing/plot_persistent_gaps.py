# ================================================================
# LOAD MASK
# ================================================================

print(f"Loading mask: {MASK_PATH}")

with xr.open_dataset(MASK_PATH) as ds:
    mask = ds["ocean_mask"].values.astype(bool)
    lat = ds["latitude"].values
    lon = ds["longitude"].values


# ================================================================
# PREPARE UNRESOLVED POINTS
# ================================================================

persistent = np.asarray(PERSISTENT_CELLS, dtype=float)

gap_lat = persistent[:, 0]
gap_lon = persistent[:, 1]

print()
print("PERSISTENT GAP SUMMARY")
print("-----------------------")
print(f"Cells:       {len(persistent)}")
print(f"Latitude:    {gap_lat.min():.2f} → {gap_lat.max():.2f}")
print(f"Longitude:   {gap_lon.min():.2f} → {gap_lon.max():.2f}")


# ================================================================
# PLOT
# ================================================================

fig = plt.figure(figsize=(15, 9))

ax = plt.axes(
    projection=ccrs.PlateCarree()
)

ax.set_extent(
    [45, 105, 5, 30],
    crs=ccrs.PlateCarree()
)


# ------------------------------------------------
# OceanEmbed computational mask
# ------------------------------------------------

lon_grid, lat_grid = np.meshgrid(lon, lat)

ax.pcolormesh(
    lon_grid,
    lat_grid,
    mask,
    transform=ccrs.PlateCarree(),
    shading="nearest",
    alpha=0.45,
)


# ------------------------------------------------
# Geographic coastlines
# ------------------------------------------------

ax.add_feature(
    cfeature.LAND,
    alpha=0.25,
    zorder=2,
)

ax.coastlines(
    resolution="50m",
    linewidth=0.8,
    zorder=3,
)


# ------------------------------------------------
# Persistent unresolved cells
# ------------------------------------------------

ax.scatter(
    gap_lon,
    gap_lat,
    s=18,
    marker=".",
    color='red',
    alpha=1.0,
    transform=ccrs.PlateCarree(),
    zorder=5,
    label=f"Persistent unresolved cells ({len(persistent)})",
)


# ================================================================
# MANUAL LAT/LON GRID
# Avoid Cartopy Gridliner because of Shapely rendering issues.
# ================================================================

# Latitude lines
for latitude in np.arange(5, 31, 5):
    ax.plot(
        [45, 105],
        [latitude, latitude],
        transform=ccrs.PlateCarree(),
        linewidth=0.5,
        linestyle="--",
        alpha=0.5,
        zorder=1,
    )

    ax.text(
        44.7,
        latitude,
        f"{latitude}°N",
        transform=ccrs.PlateCarree(),
        ha="right",
        va="center",
        fontsize=9,
    )


# Longitude lines
for longitude in np.arange(45, 106, 10):
    ax.plot(
        [longitude, longitude],
        [5, 30],
        transform=ccrs.PlateCarree(),
        linewidth=0.5,
        linestyle="--",
        alpha=0.5,
        zorder=1,
    )

    ax.text(
        longitude,
        4.6,
        f"{longitude}°E",
        transform=ccrs.PlateCarree(),
        ha="center",
        va="top",
        fontsize=9,
    )


# ================================================================
# TITLES
# ================================================================

ax.set_title(
    "OceanEmbed Persistent Unresolved Cells",
    fontsize=16,
    pad=15,
)

ax.text(
    0.5,
    1.01,
    "Computational ocean mask with unresolved target-grid cells",
    transform=ax.transAxes,
    ha="center",
    fontsize=11,
)


ax.legend(
    loc="lower left",
)


# ================================================================
# SAVE
# ================================================================

plt.tight_layout()

plt.savefig(
    OUTPUT_PATH,
    dpi=300,
    bbox_inches="tight",
)

print()
print(f"Saved map: {OUTPUT_PATH}")

plt.show()